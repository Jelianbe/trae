import re

# 方案A：非贪婪匹配
pattern_a = r'(?:对着|朝向|向着|跟着|对着|向着|跟|向|对)([\u4e00-\u9fa5]{2,4}?)(?:说道|问道|喊道|叫道|说|道|问|喊|叫|呼唤)'

# 方案B：排除后缀字符
pattern_b = r'(?:对着|朝向|向着|跟着|对着|向着|跟|向|对)([^\s说道问喊叫呼唤]{2,4})(?:说道|问道|喊道|叫道|说|道|问|喊|叫|呼唤)'

# 方案C：最小匹配（最短可能）
pattern_c = r'(?:对着|朝向|向着|跟着|对着|向着|跟|向|对)([\u4e00-\u9fa5]{2,4}?)(?:说道|问道|喊道|叫道|说|道|问|喊|叫|呼唤)'

test_cases = [
    '对着掌柜说道',
    '对着黑衣人喊道',
    '向首领报告',
    '林轩推开客栈的门，对着掌柜说道："来一间上房。"',
    '他对着黑衣人喊道："把东西交出来！"',
]

for name, pat in [('非贪婪', pattern_a), ('排除法', pattern_b), ('最小匹配', pattern_c)]:
    print(f"\n=== {name} ===")
    for text in test_cases:
        matches = re.findall(pat, text)
        print(f"  {text} -> {matches}")
